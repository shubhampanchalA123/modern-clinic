// Helper to lookup condition by slug or alias
export function getConditionData(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  if (conditionsData[cleanSlug]) {
    return conditionsData[cleanSlug];
  }
  // Search aliases
  for (const key of Object.keys(conditionsData)) {
    const item = conditionsData[key];
    if (item.aliases && item.aliases.includes(cleanSlug)) {
      return item;
    }
  }
  return null;
}

